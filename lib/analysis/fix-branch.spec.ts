import assert from 'node:assert/strict';
import {
  FIX_BRANCH_ROOT,
  fixBranchName,
  fixCommitMessage,
  fixPullRequestBody,
  fixPullRequestTitle,
  fixStageLabel,
  isBranchPushed,
} from './fix-branch.ts';

const { test, run } = (() => {
  const tests: Array<{ name: string; fn: () => void }> = [];
  return {
    test(name: string, fn: () => void) {
      tests.push({ name, fn });
    },
    async run() {
      let passed = 0;
      for (const t of tests) {
        try {
          t.fn();
          passed++;
          console.log(`ok  - ${t.name}`);
        } catch (err) {
          console.log(`FAIL- ${t.name}`);
          console.log(err instanceof Error ? err.stack : String(err));
        }
      }
      console.log(`${passed}/${tests.length} tests passed`);
      if (passed !== tests.length) process.exitCode = 1;
    },
  };
})();

test('branch names are deterministic, so a retry resumes the same branch', () => {
  const a = fixBranchName({ analysisId: '11111111-2222-3333-4444-555555555555', issueNumber: 42 });
  const b = fixBranchName({ analysisId: '11111111-2222-3333-4444-555555555555', issueNumber: 42 });
  assert.equal(a, b);
  assert.equal(a, `${FIX_BRANCH_ROOT}-issue-42-11111111`);
});

test('description-only analyses get an analysis label instead of issue-0', () => {
  const name = fixBranchName({ analysisId: 'abcdef12-9999', issueNumber: 0 });
  assert.equal(name, `${FIX_BRANCH_ROOT}-analysis-abcdef12-abcdef12`);
  assert.doesNotMatch(name, /issue-0/);
});

test('different analyses of the same issue never share a branch name', () => {
  const one = fixBranchName({ analysisId: 'aaaaaaaa-1', issueNumber: 7 });
  const two = fixBranchName({ analysisId: 'bbbbbbbb-2', issueNumber: 7 });
  assert.notEqual(one, two);
});

test('the commit message references the issue and lists the files', () => {
  const message = fixCommitMessage({
    analysisId: 'analysis-1',
    issueNumber: 7,
    patchSummary: 'Handle a missing config value.\n\nExtra detail is not the headline.',
    filesChanged: ['src/a.ts', 'src/b.ts'],
  });
  assert.match(message, /^fix: resolve issue #7\n\nHandle a missing config value\./);
  assert.match(message, /Files changed \(2\):\n- src\/a\.ts\n- src\/b\.ts/);
  assert.match(message, /Generated by BugWiser\./);
});

test('a caller-supplied commit message wins verbatim', () => {
  const message = fixCommitMessage({
    analysisId: 'analysis-1',
    issueNumber: 7,
    filesChanged: ['src/a.ts'],
    commitMessage: '  fix: custom subject  ',
  });
  assert.equal(message, 'fix: custom subject');
});

test('the pull request title and body reference the issue and the investigation', () => {
  const input = {
    analysisId: 'analysis-1',
    issueNumber: 7,
    issueUrl: 'https://github.com/owner/repo/issues/7',
    patchSummary: 'Handle a missing config value.',
    filesChanged: ['src/a.ts'],
    targetRepository: 'owner/repo',
    baseBranch: 'main',
    appBaseUrl: 'https://bugwise.example/',
    usedFork: true,
  };

  assert.equal(fixPullRequestTitle(input), 'fix: resolve issue #7');
  const body = fixPullRequestBody(input);
  assert.match(body, /## Summary\n\nHandle a missing config value\./);
  assert.match(body, /- `src\/a\.ts`/);
  assert.match(body, /Fixes \[#7\]\(https:\/\/github\.com\/owner\/repo\/issues\/7\)/);
  assert.match(body, /Investigation: https:\/\/bugwise\.example\/analysis\/analysis-1/);
  assert.match(body, /lives on a fork/);
});

test('a same-repository PR body says the default branch was not modified', () => {
  const body = fixPullRequestBody({
    analysisId: 'analysis-1',
    filesChanged: [],
    targetRepository: 'owner/repo',
    baseBranch: 'main',
    usedFork: false,
  });
  assert.match(body, /default branch was not modified/);
});

test('stage labels describe the confirmed state, not an intention', () => {
  assert.equal(fixStageLabel('awaiting_authorization'), 'GitHub authorization required');
  assert.equal(fixStageLabel('branch_created'), 'Fix branch created');
  assert.equal(fixStageLabel('pr_created'), 'Pull Request created successfully');
  assert.equal(fixStageLabel('pr_failed'), 'Branch pushed, Pull Request failed');
  assert.equal(fixStageLabel('none'), 'Not started');
});

test('a pushed branch is never considered unpushed after a transient PR error', () => {
  assert.equal(isBranchPushed('pushed'), true);
  assert.equal(isBranchPushed('creating_pr'), true);
  assert.equal(isBranchPushed('pr_created'), true);
  assert.equal(isBranchPushed('pr_failed'), true);
  assert.equal(isBranchPushed('committed'), false);
  assert.equal(isBranchPushed('failed'), false);
});

run().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
