// Pure naming and text rules for the branch → commit → pull request workflow.
//
// Kept free of network, database, and framework imports so the exact branch
// name, commit message, and pull request body are unit-testable. Determinism is
// load-bearing: the same analysis must always map to the same branch name, which
// is what makes a retry resume instead of creating a second branch.

import type { FixStatus } from '../../types/index.ts';

export const FIX_BRANCH_ROOT = 'bugwiser/fix';

const MAX_REF_LENGTH = 200;

export interface FixBranchInput {
  analysisId: string;
  issueNumber?: number | null;
}

/**
 * `bugwiser/fix-issue-42-1a2b3c4d` for an issue analysis, or
 * `bugwiser/fix-analysis-1a2b3c4d` for a description-only one.
 *
 * The analysis-id prefix guarantees uniqueness across analyses of the same
 * issue without a random suffix, so a retry addresses the same branch.
 */
export function fixBranchName(input: FixBranchInput): string {
  const shortId = (input.analysisId || '').replace(/[^A-Za-z0-9]/g, '').slice(0, 8) || 'unknown';
  const label =
    input.issueNumber && input.issueNumber > 0
      ? `issue-${input.issueNumber}`
      : `analysis-${shortId}`;
  const name = `${FIX_BRANCH_ROOT}-${label}-${shortId}`;
  return name.slice(0, MAX_REF_LENGTH);
}

export interface FixCommitInput {
  analysisId: string;
  issueNumber?: number | null;
  patchSummary?: string | null;
  filesChanged: readonly string[];
  /** Caller-supplied message wins (already trimmed). */
  commitMessage?: string | null;
}

export function fixCommitMessage(input: FixCommitInput): string {
  if (input.commitMessage && input.commitMessage.trim()) {
    return tidyMessage(input.commitMessage.trim());
  }

  const reference =
    input.issueNumber && input.issueNumber > 0
      ? `issue #${input.issueNumber}`
      : `analysis ${shortId(input.analysisId)}`;

  const summary = tidyMessage((input.patchSummary || '').trim()).split('\n')[0];
  const headline = summary ? `fix: resolve ${reference}\n\n${summary}` : `fix: resolve ${reference}`;
  const fileLines = input.filesChanged.length
    ? `\n\nFiles changed (${input.filesChanged.length}):\n${input.filesChanged
        .map((path) => `- ${path}`)
        .join('\n')}`
    : '';

  return `${headline}${fileLines}\n\nGenerated by BugWiser.`;
}

export interface FixPullRequestInput {
  analysisId: string;
  issueNumber?: number | null;
  issueUrl?: string | null;
  patchSummary?: string | null;
  filesChanged: readonly string[];
  targetRepository: string;
  baseBranch: string;
  /** Public application URL, used for a link back to the investigation. */
  appBaseUrl?: string | null;
  usedFork?: boolean;
}

export function fixPullRequestTitle(input: FixPullRequestInput): string {
  if (input.issueNumber && input.issueNumber > 0) {
    return `fix: resolve issue #${input.issueNumber}`;
  }
  const summary = tidyMessage((input.patchSummary || '').trim()).split('\n')[0];
  return summary ? `fix: ${summary.slice(0, 100)}` : `fix: BugWiser analysis ${shortId(input.analysisId)}`;
}

export function fixPullRequestBody(input: FixPullRequestInput): string {
  const sections: string[] = [];

  sections.push('## Summary');
  sections.push(
    input.patchSummary?.trim() ||
      'This pull request applies a change proposed by a BugWiser investigation.'
  );

  if (input.filesChanged.length > 0) {
    sections.push('## Changes');
    sections.push(input.filesChanged.map((path) => `- \`${path}\``).join('\n'));
  }

  const related: string[] = [];
  if (input.issueNumber && input.issueNumber > 0) {
    related.push(
      input.issueUrl
        ? `Fixes [#${input.issueNumber}](${input.issueUrl}).`
        : `Fixes issue #${input.issueNumber}.`
    );
  }
  if (input.appBaseUrl) {
    related.push(
      `Investigation: ${trimTrailingSlash(input.appBaseUrl)}/analysis/${input.analysisId}`
    );
  }
  if (related.length > 0) {
    sections.push('## Related');
    sections.push(related.join('\n'));
  }

  sections.push('## Notes');
  sections.push(
    [
      `- Base branch: \`${input.baseBranch}\` on \`${input.targetRepository}\`.`,
      input.usedFork
        ? '- This branch lives on a fork because the author does not have write access to the original repository.'
        : '- The default branch was not modified; these changes exist only on the fix branch.',
      '- Generated by BugWiser from an approved investigation. Review before merging.',
    ].join('\n')
  );

  return sections.join('\n\n');
}

/** Human-readable progress text for one persisted status. */
export function fixStageLabel(status: FixStatus | null | undefined): string {
  switch (status) {
    case 'awaiting_authorization':
      return 'GitHub authorization required';
    case 'branch_creating':
      return 'Creating fix branch…';
    case 'branch_created':
      return 'Fix branch created';
    case 'committing':
      return 'Applying approved changes…';
    case 'committed':
      return 'Changes committed';
    case 'pushing':
      return 'Pushing fix branch…';
    case 'pushed':
      return 'Fix branch pushed';
    case 'creating_pr':
      return 'Creating Pull Request…';
    case 'pr_created':
      return 'Pull Request created successfully';
    case 'pr_failed':
      return 'Branch pushed, Pull Request failed';
    case 'failed':
      return 'Fix workflow failed';
    default:
      return 'Not started';
  }
}

/** Stages after which the branch is already on GitHub. */
export function isBranchPushed(status: FixStatus | null | undefined): boolean {
  return (
    status === 'pushed' ||
    status === 'creating_pr' ||
    status === 'pr_created' ||
    status === 'pr_failed'
  );
}

function shortId(analysisId: string): string {
  return (analysisId || '').replace(/[^A-Za-z0-9]/g, '').slice(0, 8) || 'unknown';
}

function tidyMessage(value: string): string {
  return value.replace(/\r\n/g, '\n').trim();
}

function trimTrailingSlash(value: string): string {
  return value.replace(/\/+$/, '');
}
